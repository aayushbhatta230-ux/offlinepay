// Builds site/: the standalone wallet as a website (GitHub Pages), for iPhone and any phone browser.
// Same app as the APK — the whole backend runs in the browser — plus an offline cache and
// home-screen support. All paths are relative because Pages serves it from /<repo>/.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(import.meta.dirname, '..');
const out = path.join(root, 'site');
const files = [];

const write = (to, content) => {
  fs.mkdirSync(path.dirname(path.join(out, to)), { recursive: true });
  fs.writeFileSync(path.join(out, to), content);
  files.push(to);
};
const read = (from) => fs.readFileSync(path.join(root, from));

fs.rmSync(out, { recursive: true, force: true });

write('app.js', read('apps/wallet/app.js').toString().replace("from '/sdk/", "from './sdk/"));
write('local-backend.js', read('apps/wallet/local-backend.js').toString().replaceAll("from '/core/", "from './core/"));
write('styles.css', read('apps/wallet/styles.css'));
write('icons.js', read('apps/wallet/icons.js'));
for (const f of ['offlinepay-sdk.js', 'protocol.js']) write(`sdk/${f}`, read(`sdk/${f}`));
for (const f of ['engine.js', 'passwords-web.js', 'demo-issuer.js']) write(`core/${f}`, read(`core/${f}`));
write('vendor/qrcode.js', read('node_modules/qrcode-generator/qrcode.js'));
write('vendor/jsQR.js', read('node_modules/jsqr/dist/jsQR.js'));
for (const f of ['apple-touch-icon.png', 'icon-192.png', 'icon-512.png']) write(`web-icons/${f}`, read(`apps/wallet/web-icons/${f}`));

write('manifest.webmanifest', JSON.stringify({
  name: 'OfflinePay Wallet',
  short_name: 'OfflinePay',
  description: 'Demo digital wallet that keeps working without internet.',
  start_url: './',
  scope: './',
  display: 'standalone',
  background_color: '#2b7a2b',
  theme_color: '#3d9a3d',
  icons: [
    { src: 'web-icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any maskable' },
    { src: 'web-icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any maskable' },
  ],
}, null, 2));

const html = read('apps/wallet/index.html').toString()
  .replaceAll('src="/vendor/', 'src="./vendor/')
  .replace('<title>Wallet</title>', `<title>OfflinePay Wallet</title>
  <meta name="apple-mobile-web-app-capable" content="yes">
  <meta name="mobile-web-app-capable" content="yes">
  <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
  <meta name="apple-mobile-web-app-title" content="OfflinePay">
  <link rel="apple-touch-icon" href="web-icons/apple-touch-icon.png">
  <link rel="icon" href="web-icons/icon-192.png">`)
  .replace('<script src="./vendor/qrcode.js">', '<script>window.OPAY_NATIVE = true;</script>\n  <script src="./vendor/qrcode.js">');
write('index.html', html);

// Service worker: precache every file so the app opens in airplane mode after the first visit.
// The cache name changes whenever any file changes, so updates reach phones on the next online open.
const hash = crypto.createHash('sha256');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(out, f)));
const version = hash.digest('hex').slice(0, 12);
write('sw.js', `// Generated by scripts/build-web.js
const CACHE = 'offlinepay-web-${version}';
const FILES = ${JSON.stringify(['./', ...files])};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Network first (so a fresh version shows when online), cached copy when offline.
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(
    fetch(e.request)
      .then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
        return res;
      })
      .catch(() => caches.match(e.request, { ignoreSearch: true }).then((r) => r || caches.match('./')))
  );
});
`);
fs.writeFileSync(path.join(out, '.nojekyll'), '');

console.log(`Built site/ (${files.length} files, version ${version})`);
