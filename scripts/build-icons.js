// Generates apps/wallet/icons.js from Lucide (ISC license) so the app ships only the icons it uses.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const NAMES = [
  'house', 'file-text', 'scan-line', 'wallet', 'user', 'bell', 'eye', 'eye-off', 'circle-plus', 'send',
  'arrow-down-left', 'smartphone', 'zap', 'droplet', 'wifi', 'tv', 'graduation-cap', 'shield-check', 'plane',
  'bus', 'clapperboard', 'landmark', 'layout-grid', 'wifi-off', 'lock', 'refresh-cw', 'chevron-right',
  'arrow-left', 'circle-help', 'log-out', 'settings', 'activity', 'trash-2', 'circle-check', 'circle-x',
  'triangle-alert', 'camera', 'copy', 'shield-alert', 'qr-code', 'building-2', 'history', 'store',
];

const icons = {};
for (const n of NAMES) {
  const svg = fs.readFileSync(path.join(root, 'node_modules', 'lucide-static', 'icons', `${n}.svg`), 'utf8');
  icons[n] = svg.replace(/<!--.*?-->/s, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].replace(/\s*\n\s*/g, '').trim();
}

const out = `// Generated by scripts/build-icons.js from lucide-static (ISC license). Do not edit.
const PATHS = ${JSON.stringify(icons)};
export const icon = (name, size = 22) =>
  \`<svg class="ic-svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${PATHS[name] || ''}</svg>\`;
`;
fs.writeFileSync(path.join(root, 'apps', 'wallet', 'icons.js'), out);
console.log(`Wrote ${NAMES.length} icons`);
